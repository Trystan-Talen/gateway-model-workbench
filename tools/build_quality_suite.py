def add(cat, title, prompt, answer, reason, wrong, kind='exact_text', critical=False):
    n = sum(c['category'] == cat for c in CASES) + 1
    if kind == 'json_exact':
        suffix = '\n只输出一个合法 JSON（结构化数据）值，不用代码块，不增减字段；数组保持要求的顺序。'
        reference = json.dumps(answer, ensure_ascii=False, separators=(',', ':'))
        negatives = [json.dumps(wrong, ensure_ascii=False), reference + '\n以上是答案', '```json\n' + reference + '\n```']
    else:
        suffix = '\n只输出指定答案，不加解释、引号或代码块。'
        reference = str(answer)
        negatives = [str(wrong), '答案是：' + reference, reference + '，另一个答案是' + str(wrong)]
    CASES.append(dict(id=f'{cat}_{n:02d}', category=cat, title=title, prompt=prompt+suffix,
                      difficulty='基础' if n<=4 else '进阶' if n<=8 else '挑战', objective=title,
                      request={'temperature':0, 'stream':False, 'max_tokens':1024}, weight=1,
                      evaluator={'type':kind, 'expected':answer}, reference_answer=reference,
                      rationale=reason, negative_examples=negatives, critical=critical,
                      source='本项目原创合成场景；不涉及真实个人数据'))

